const preferenceKey = "umbral:language";
export function detectLanguage(preference, browserLanguage) {
  if (preference === "es" || preference === "en") return preference;
  return /^es(?:-|$)/i.test(browserLanguage || "") ? "es" : "en";
}
function initialLanguage() {
  if (typeof window === "undefined") return "en";
  let saved;
  try {
    saved = localStorage.getItem(preferenceKey);
  } catch {}
  const override = new URL(location.href).searchParams.get("lang");
  return detectLanguage(
    ["en", "es"].includes(override) ? override : saved,
    navigator.languages?.[0] || navigator.language,
  );
}
export const language = initialLanguage();
export const t = (key) =>
  language === "en" && Object.hasOwn(english, key) ? english[key] : key;
export function switchLanguage() {
  const next = language === "en" ? "es" : "en",
    url = new URL(location.href);
  try {
    localStorage.setItem(preferenceKey, next);
    url.searchParams.delete("lang");
  } catch {
    url.searchParams.set("lang", next);
  }
  location.replace(url.href);
}
export function localizeShell(root) {
  for (const el of root.querySelectorAll("[data-es]"))
    el.textContent = t(el.dataset.es);
  for (const el of root.querySelectorAll("[data-es-label]"))
    el.setAttribute("aria-label", t(el.dataset.esLabel));
}
