export function icon(name, size = 18) {
  const el = createElement(icons[name] || Box);
  el.setAttribute("width", size);
  el.setAttribute("height", size);
  el.setAttribute("stroke-width", "1.65");
  el.setAttribute("aria-hidden", "true");
  return el.outerHTML;
}
